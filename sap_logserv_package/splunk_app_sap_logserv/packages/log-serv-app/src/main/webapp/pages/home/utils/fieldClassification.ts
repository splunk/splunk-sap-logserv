const hasOwn = (o: object, k: string): boolean => Object.prototype.hasOwnProperty.call(o, k);

/** The class of a field name, exactly as written (case included); undefined for a name neither table holds. */
export const fieldClassOf = (name: string): FieldClass | undefined => {
    if (typeof name !== 'string') return undefined;
    if (hasOwn(FIELD_CLASSES, name)) return FIELD_CLASSES[name];
    if (hasOwn(SPLUNK_FIELD_CLASSES, name)) return SPLUNK_FIELD_CLASSES[name];
    return undefined;
};

/**
 * True when the table marks the name an identifier: an `identifier` or an
 * `address`, or a `host` with the hostname opt-in.
 */
export const isClassifiedIdentifier = (name: string, redactHostnames = false): boolean => {
    const c = fieldClassOf(name);
    return c === 'identifier' || c === 'address' || (c === 'host' && redactHostnames);
};
