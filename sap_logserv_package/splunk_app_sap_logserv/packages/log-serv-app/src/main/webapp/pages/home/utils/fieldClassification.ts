/**
 * fieldClassification - every field name the App defines, with the class of
 * value it holds (App build 377, AI-a2-names option B).
 *
 * Why this exists. Tier 2 redaction decides by NAME whether a column holds an
 * identifier (`isIdentifierColumnName` in utils/vendorColumnText.ts). Until
 * build 376 that was an open-ended list of name patterns, and the App's own
 * fields slipped through it: `object` (a HANA audit target user), `command`
 * and `sql_statement` (statements that name users), `local_ip`, `peer_ip`,
 * `ip`, lastlog's `FROM`, `fw_dst`, `label` and `canonical_value` (topology
 * host names and addresses), `supplied_by`. This table classifies every name
 * the App defines - in default/props.conf (EXTRACT groups, EVAL, FIELDALIAS
 * targets, LOOKUP outputs), default/transforms.conf (REGEX groups, FORMAT
 * targets, fields_list), default/collections.conf (`field.*`) and the
 * lookups/*.csv headers - and fieldClassification.consistency-test parses
 * those files the same way and FAILS THE BUILD on any App field without a
 * class, so a new extraction cannot ship unclassified.
 *
 * The classes:
 *   - `identifier`: names or carries a person, an account or a session -
 *     user names, statements that name them, search and object ids;
 *   - `address`: an IP address, a MAC or a field that holds an address or a
 *     host name in one (the CIM `src` / `dest` / `dvc`), and the host name
 *     of a client workstation, which can name the person who uses it;
 *   - `host`: a server's host name - redacted only with the admin's
 *     hostname opt-in;
 *   - `free_text`: free-form text (messages, URLs, SPL); not redacted by name
 *     (name-based redaction is hygiene for ordinary queries, not a content
 *     filter - see the privacy-tiers docs);
 *   - `safe`: categorical and numeric fields.
 *
 * How it is used: an `identifier` or `address` name is an identifier, a
 * `host` name is one with the hostname opt-in. The name patterns of
 * utils/piiRedaction.ts stay in force as well, for every name (the App's
 * and any other), so the table can only ADD identifiers; the suite also
 * checks that no name the patterns mark is classified weaker here - so a
 * few flags whose NAME a pattern marks (`is_admin_user`, `trend_src`,
 * `tier2_redact_hostnames`) carry the class the pattern gives them.
 *
 * A rollup column takes the strongest class of what its rollup search
 * writes into it (security review of build 377): `operator`
 * (logserv_compliance_rollup: "HANA:" . executing_user, "Windows:" .
 * SubjectUserName, "Linux:" . os_user) and `error_detail`
 * (logserv_topology_detail_rollup: executing_user on hana_audit rows) are
 * identifiers; `scope` (logserv_topology_detail_rollup: peer / local /
 * client IP addresses or the host) and `spl_filter_clauses`
 * (logserv_topology_edges: JSON holding clientip / client_ip / host values)
 * are addresses. All four are readable through `| inputlookup`.
 *
 * App build 378 adds the fields of its new extractions: the SAP Router
 * CONNECT TO target (`saprouter_target_addr`, `saprouter_target_ip` and
 * `saprouter_fail_target_ip` are addresses; the target's SID, service, role
 * and instance number are categorical), the gateway's connection records
 * (`gw_remgw_target` - a host name, an IP address or a SAP Router route
 * string - `gw_client_ip` and the external RFC client's workstation
 * `gw_client_hostname` are addresses; the connection numbers are
 * identifiers like `connection_id`; services, programs and ports are
 * categorical), the HANA
 * audit client host `src_host` (an address, the twin of `dest_host`: the
 * search-time `host` of a HANA audit record is the HANA host again) and the
 * HANA trace fields `hana_backup_level`, `hana_trace_file_type`,
 * `hana_op_duration` and `hana_op_duration_unit` (categorical and numeric).
 * Item icm adds the dev_icm fields: the SAP client of a session-list line
 * `sap_client`, the trace message class `icm_severity` and the connection
 * direction `icm_conn_role` (categorical), the session's SAP user
 * `icm_user` (an identifier) and its terminal `icm_terminal` (an IP address
 * or a front-end host name: an address); `icm_status_code` is gone - it was
 * the SAP client read as an HTTP status.
 *
 * Client workstation names (user decision for build 378): the host name
 * of a client workstation can name the person who uses it, so it is an
 * `address` - redacted in Tier 2 by default, not only with the hostname
 * opt-in: `audit_hostname` (the HANA audit client's host name, which
 * props aliases as `src_host`; a `host` until build 378) and the RFC
 * client's `gw_client_hostname`. A server's host name stays `host`:
 * `db_hostname` (the HANA host the audit record names), `hana_host`,
 * `Computer`.
 *
 * Pure: no imports - loadable by bin/check-diagnostics.js.
 */

