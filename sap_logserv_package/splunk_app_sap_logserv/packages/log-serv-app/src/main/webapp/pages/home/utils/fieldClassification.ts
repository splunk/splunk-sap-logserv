/**
 * Names Splunk itself (or a CIM data model) defines that the App's searches
 * or an ad-hoc query can produce, classified the same way: `info_sid` (from
 * `addinfo`) is the search id, which carries the user name; `identity` /
 * `identities` are the CIM identity fields. Security review of build 377:
 * the fields Splunk's automatic key-value extraction gives the LogServ Linux
 * sourcetypes, which set no KV_MODE - pam's `rhost` (an address), `ruser`,
 * `logname` and `euid`, and sudo's `PWD` (a home directory names its user)
 * and `COMMAND` (like the App's own `command`).
 */
